def parse_row(s):
    s = s.replace("◆", "")  # ◆ は装飾記号として除去
    entries = []
    pos = 0
    n = len(s)
    while pos < n:
        ttype = "普通"  # 普通(デフォルト)
        for code, _label, cat in TYPE_CODES:
            if s.startswith(code, pos):
                ttype = cat
                pos += len(code)
                break
        # 分(1〜2桁)
        start = pos
        while pos < n and s[pos].isdigit() and (pos - start) < 2:
            pos += 1
        if pos == start:
            raise ValueError(f"digit expected at {pos} in {s!r}")
        minute = int(s[start:pos])
        # 行先コード(長い順)
        dest = None
        for code in DEST_KEYS:
            if s.startswith(code, pos):
                dest = DEST_CODES[code]
                pos += len(code)
                break
        if dest is None:
            raise ValueError(f"dest code not found at {pos} in {s!r} (remaining: {s[pos:pos+5]!r})")
        entries.append({"type": ttype, "min": minute, "dest": dest})
    return entries


